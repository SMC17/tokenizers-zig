#!/usr/bin/env python3
"""Observe the pinned HF BertPreTokenizer predicate for every Unicode scalar."""
import argparse
import hashlib
from pathlib import Path
import tokenizers
from tokenizers.pre_tokenizers import BertPreTokenizer

VERSION = "0.21.4"
ROOT = Path(__file__).resolve().parents[1]


def generate():
    if tokenizers.__version__ != VERSION:
        raise RuntimeError(f"Need tokenizers=={VERSION}; found {tokenizers.__version__}")
    reference = BertPreTokenizer()
    points = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        pieces = reference.pre_tokenize_str("a" + char + "b")
        if [part for part, _ in pieces] == ["a", char, "b"]:
            points.append(cp)
    ranges = []
    for cp in points:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    digest = hashlib.sha256(b"".join(cp.to_bytes(4, "little") for cp in points)).hexdigest()
    lines = [
        "//! Generated by tools/generate_bert_punctuation.py with HF tokenizers 0.21.4.",
        "//! Observed on every Unicode scalar using the original a<scalar>b probe.",
        "//! This pins the reference's punctuation behavior, not general Unicode normalization.",
        f"//! {len(points)} punctuation scalars; little-endian-u32 list SHA-256: {digest}",
        "", "pub fn contains(cp: u21) bool {", "    return switch (cp) {",
    ]
    for lo, hi in ranges:
        pattern = f"0x{lo:X}" if lo == hi else f"0x{lo:X}...0x{hi:X}"
        lines.append(f"        {pattern} => true,")
    lines += ["        else => false,", "    };", "}", ""]
    return "\n".join(lines), len(points), len(ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Replace the generated predicate; default checks it")
    args = parser.parse_args()
    text, points, ranges = generate()
    path = ROOT / "src/bert_punctuation.zig"
    if args.write:
        path.write_text(text)
    elif path.read_text() != text:
        raise RuntimeError("Generated punctuation table differs")
    print(f"BERT_PUNCTUATION_OK reference={VERSION} scalars=1112064 punctuation={points} ranges={ranges}")


if __name__ == "__main__":
    main()
