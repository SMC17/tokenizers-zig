#!/usr/bin/env bash
# checkpoint.sh — write NEXT.md capturing the current session state so
# the next session (Claude or otherwise) can pick up cleanly.
#
# Captured fields:
#   - Last 3 commits (sha + subject)
#   - Working-tree status summary (modified count, untracked count)
#   - Open stax-experiment ids for the current repo's lane (if the
#     stax-experiment binary is on PATH; otherwise that section is
#     skipped silently)
#   - Next-action hint (manually edited by the developer/Claude in
#     between commits — preserved across regenerations via a "## Next
#     concrete action" sentinel section).
#
# Sovereign: pure bash + git + optional stax-experiment. Doesn't
# require Claude to be running.
#
# Usage:
#   ./scripts/checkpoint.sh                    # writes NEXT.md
#   ./scripts/checkpoint.sh --lane <name>      # override lane name
#   ./scripts/checkpoint.sh --dry-run          # print to stdout, don't write

set -euo pipefail

LANE=""
DRY_RUN=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --lane)     LANE="$2"; shift 2 ;;
    --dry-run)  DRY_RUN=1;  shift ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

# Repo root
REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$REPO_ROOT"

# Lane defaults to the repo basename
[[ -z "$LANE" ]] && LANE="$(basename "$REPO_ROOT")"

# Gather state
LAST_COMMITS="$(git log --oneline -3 2>/dev/null || echo '(no commits yet)')"
# grep -c prints "0" + exits 1 on no-match — use `|| true` and trust the printed count.
MODIFIED_COUNT="$(git status --short 2>/dev/null | grep -c '^ M' || true)"
UNTRACKED_COUNT="$(git status --short 2>/dev/null | grep -c '^??' || true)"
STAGED_COUNT="$(git status --short 2>/dev/null | grep -cE '^[MADRC]' || true)"
# Defensive — collapse any blank to "0".
[[ -z "$MODIFIED_COUNT" ]] && MODIFIED_COUNT=0
[[ -z "$UNTRACKED_COUNT" ]] && UNTRACKED_COUNT=0
[[ -z "$STAGED_COUNT" ]] && STAGED_COUNT=0

# Open stax-experiment ids in this lane (if binary available)
OPEN_EXPERIMENTS=""
if command -v stax-experiment >/dev/null 2>&1; then
  OPEN_EXPERIMENTS="$(stax-experiment open 2>/dev/null | grep -F "\"lane\":\"${LANE}\"" | head -10 || true)"
fi

# Preserve manually-written "Next concrete action" if NEXT.md already exists.
NEXT_ACTION_BLOCK=""
if [[ -f NEXT.md ]]; then
  NEXT_ACTION_BLOCK="$(awk '/^## Next concrete action/,/^## /' NEXT.md | head -n -1 | tail -n +2 || true)"
fi
[[ -z "$NEXT_ACTION_BLOCK" ]] && NEXT_ACTION_BLOCK="_(no manual hint set — edit NEXT.md after a commit to record the next concrete step)_"

# Render
OUT=$(cat <<EOF
# NEXT — ${LANE}

_Last update: $(date -u +%Y-%m-%dT%H:%M:%SZ) (auto-generated by scripts/checkpoint.sh)_

## What just shipped

\`\`\`
${LAST_COMMITS}
\`\`\`

## Working-tree state

- Modified: ${MODIFIED_COUNT}
- Untracked: ${UNTRACKED_COUNT}
- Staged: ${STAGED_COUNT}

## Open hypotheses (stax-experiment lane=${LANE})

EOF
)

if [[ -n "$OPEN_EXPERIMENTS" ]]; then
  OUT+="$(printf '\n```\n%s\n```\n' "$OPEN_EXPERIMENTS")"
else
  OUT+=$'\n_(none open or stax-experiment not on PATH)_\n'
fi

OUT+="

## Next concrete action

${NEXT_ACTION_BLOCK}

## How to regenerate

\`\`\`
./scripts/checkpoint.sh
\`\`\`

Or enable the post-commit hook once:

\`\`\`
git config core.hooksPath .githooks
\`\`\`
"

if [[ "$DRY_RUN" -eq 1 ]]; then
  printf '%s\n' "$OUT"
else
  printf '%s\n' "$OUT" > NEXT.md
fi
